-- Ejecutar una sola vez en Supabase: SQL Editor > New query.
-- Mantiene los avisos separados de GitHub y permite lectura pública,
-- pero solo usuarios autenticados pueden publicar o eliminar.

create table if not exists public.avisos (
    id bigint generated by default as identity primary key,
    titulo text not null,
    fecha date not null,
    resumen text not null,
    enlace_facebook text,
    created_at timestamptz not null default now()
);

alter table public.avisos enable row level security;

create policy "Avisos visibles para todos"
on public.avisos for select
to anon, authenticated
using (true);

create policy "Administradores autenticados pueden publicar"
on public.avisos for insert
to authenticated
with check (true);

create policy "Administradores autenticados pueden eliminar"
on public.avisos for delete
to authenticated
using (true);
